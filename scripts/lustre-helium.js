// lustre-helium.js - ванильная турель Сияние (lustre) работает на азоте ИЛИ на гелии.
//
// ---- Что меняется ----
// У каждого блока есть список потребления (consumers): что ему нужно для работы.
// У Сияния в коде игры (Blocks.java) записано:
//     consumeLiquid(Liquids.nitrogen, 6f / 60f);   -> ConsumeLiquid: строго азот, 6 в секунду
//     consumePower(200f / 60f);                    -> ConsumePower: энергия, 200 в секунду
// Азот здесь не боеприпас: Сияние всегда стреляет одним и тем же лучом, а азот - обязательное
// потребление, как энергия. Если газа не хватает, урон луча падает пропорционально.
//
// Скрипт заменяет первый пункт на ConsumeLiquidFilter - "любая жидкость, подходящая под фильтр".
// Фильтр - обычная функция: получает жидкость и отвечает true (подходит) или false.
// Здесь подходят азот и гелий. Расход берётся из старого пункта (6 в секунду), энергия не трогается.
//
// ---- Почему именно скрипт и почему это успевает сработать ----
// Игра загружает моды в таком порядке:
//   1) создаёт ванильный контент - Blocks.lustre уже существует;
//   2) запускает скрипты модов                          <- этот файл выполняется здесь;
//   3) создаёт контент модов из JSON - здесь появляется наш гелий;
//   4) инициализирует все блоки (init): список потребления превращается в окончательный массив,
//      а блок запоминает, какие жидкости ему можно подавать по трубам.
// Менять список потребления можно только до шага 4, потом игра бросает ошибку.
// На шаге 2 гелия ещё нет, поэтому фильтр ищет его по имени при первом вызове (на шаге 4 и позже).
//
// В JSON-патче так сделать нельзя: там есть только "одна жидкость", "все эти жидкости сразу"
// и "любой хладагент", а последний турель считает необязательным охлаждением и стреляла бы без газа.
//
// ---- Что видно в игре ----
// В окне Сияния вместо значка азота чередуются азот и гелий, в характеристиках - обе жидкости.
// Если в турель приходят оба газа, она тратит тот, что пришёл последним, а когда он кончится - другой.
// Полоска заряда показывает только, хватает ли газа: уровень бака игра считает лишь для турелей
// с одной конкретной жидкостью.
//
// Если что-то пойдёт не так, Сияние остаётся ванильным (только азот), ошибка пишется в last_log.txt.

const HELIUM_NAME = "termoatom-helium";

let helium = null;

// Подходит ли жидкость как "топливо" для луча.
// Функцию вызывает сама игра (при инициализации и во время стрельбы), поэтому внутри не должно быть
// ни одной ошибки: исключение здесь уронило бы игру. Отсюда try/catch.
function isLustreGas(liquid){
    try{
        if(liquid == Liquids.nitrogen) return true;
        if(helium == null) helium = Vars.content.liquid(HELIUM_NAME);
        return helium != null && liquid == helium;
    }catch(e){
        return false;
    }
}

function patchLustre(){
    const lustre = Blocks.lustre;

    // Находим ванильный пункт "азот". Если его нет (например, Сияние уже изменил другой мод),
    // ничего не трогаем.
    const old = lustre.findConsumer(c => c instanceof ConsumeLiquid && c.liquid == Liquids.nitrogen);
    if(old == null){
        Log.warn("[lustre-helium] У Сияния нет потребления азота - турель не изменена.");
        return;
    }

    // Сначала создаём новый пункт, потом убираем старый: если создание не удастся,
    // турель останется как была, а не без потребления газа вообще.
    const gas = new ConsumeLiquidFilter(isLustreGas, old.amount);

    lustre.removeConsumer(old);
    lustre.consume(gas);

    print("lustre-helium: Сияние работает на азоте или гелии");
}

try{
    patchLustre();
}catch(e){
    Log.err("[lustre-helium] Не удалось изменить Сияние, оно остаётся ванильным: " + e);
}
